import { useCallback, useEffect, useState } from 'react';
import { api } from '../services/api';
import AppList from '../components/AppList';
import AppPanel from '../components/AppPanel';
import { AlertsPanel, EventLog, Timeline, UsageChart } from '../components/Insights';

export default function Dashboard({ user, onSignOut }) {
  const [apps, setApps] = useState([]);
  const [stats, setStats] = useState(null);
  const [alerts, setAlerts] = useState([]);
  const [events, setEvents] = useState([]);
  const [selected, setSelected] = useState(null);
  const [live, setLive] = useState(false);
  const [error, setError] = useState('');

  const refresh = useCallback(async () => {
    try {
      const [a, s, al, ev] = await Promise.all([api.apps(), api.dashboard(), api.alerts(), api.events()]);
      setApps(a); setStats(s); setAlerts(al); setEvents(ev); setError('');
      setSelected((cur) => cur && a.some((x) => x._id === cur) ? cur : a[0]?._id || null);
    } catch (e) { setError(e.message); }
  }, []);

  useEffect(() => { refresh(); }, [refresh]);

  // Simulated live monitoring: one random event every 3 seconds
  useEffect(() => {
    if (!live) return;
    const id = setInterval(async () => {
      try { await api.simulate('random'); await refresh(); } catch (e) { setError(e.message); setLive(false); }
    }, 3000);
    return () => clearInterval(id);
  }, [live, refresh]);

  const seed = async () => {
    try { setError(''); await api.seed(); await refresh(); }
    catch (e) { setError(e.message); }
  };
  const current = apps.find((a) => a._id === selected);
  const cards = stats && [
    ['Monitored apps', stats.monitoredApps], ['Suspicious apps', stats.suspiciousApps],
    ['Access events', stats.accessEvents], ['Security alerts', stats.securityAlerts],
  ];

  return (
    <div className="min-h-screen">
      <header className="bg-ink text-white">
        <div className="max-w-7xl mx-auto px-4 py-3 flex flex-wrap items-center gap-3 justify-between">
          <p className="text-lg font-semibold tracking-wide">E.D.I.T.H.</p>
          <div className="flex items-center gap-3 text-sm">
            <button onClick={() => setLive(!live)} aria-pressed={live}
              className={`rounded px-3 py-1.5 font-medium ${live ? 'bg-danger' : 'bg-signal'}`}>
              {live ? 'Stop live simulation' : 'Start live simulation'}
            </button>
            <span className="text-white/70">{user.name}</span>
            <button onClick={onSignOut} className="underline text-white/80">Sign out</button>
          </div>
        </div>
        <p className="bg-caution/90 text-white text-xs text-center py-1">
          Simulated monitoring: events are generated by sample apps, not read from your device.
        </p>
      </header>

      <main className="max-w-7xl mx-auto p-4 space-y-4">
        {error && <p role="alert" className="rounded border border-danger/40 bg-danger/10 text-danger p-3 text-sm">{error}</p>}

        {cards && (
          <div className="grid grid-cols-2 md:grid-cols-4 gap-3">
            {cards.map(([label, value]) => (
              <div key={label} className="bg-white border border-line rounded-lg p-4">
                <p className="text-sm text-mute">{label}</p>
                <p className={`text-3xl font-bold tabular-nums ${label === 'Suspicious apps' && value > 0 ? 'text-danger' : ''}`}>{value}</p>
              </div>
            ))}
          </div>
        )}

        <div className="grid lg:grid-cols-[320px_1fr] gap-4 items-start">
          <AppList apps={apps} selectedId={selected} onSelect={setSelected} onSeed={seed} />
          <div className="grid xl:grid-cols-2 gap-4 items-start">
            {current ? <AppPanel key={current._id} app={current} onChange={refresh} /> : <div />}
            <div className="space-y-4">
              <AlertsPanel alerts={alerts} />
              <UsageChart usage={stats?.usage} />
              <Timeline events={events} />
              <EventLog events={events} />
            </div>
          </div>
        </div>
      </main>
    </div>
  );
}
